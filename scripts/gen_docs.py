"""Regenerate the documentation and manifests that are derived from the code.

Usage::

    python scripts/gen_docs.py           # rewrite the generated files
    python scripts/gen_docs.py --check   # exit 1 if any of them is out of date

What it owns:

- ``docs/reference.md``: every MCP tool (signature and description, from the server)
  and every registered check (from the registry).
- The version in ``.claude-plugin/plugin.json``, ``.claude-plugin/marketplace.json``
  and ``server.json``, taken from ``ardupilot_mcp.__version__``, and the license in
  ``plugin.json``.

``tests/test_docs_sync.py`` runs the check, so CI fails when a change to the code is
not reflected here.
"""

from __future__ import annotations

import asyncio
import json
import sys
import tomllib
from collections.abc import Callable
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from ardupilot_mcp import __version__  # noqa: E402
from ardupilot_mcp.checks import get_checks  # noqa: E402
from ardupilot_mcp.server import mcp  # noqa: E402

LICENSE = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]["license"]
REFERENCE = ROOT / "docs" / "reference.md"
PLUGIN = ROOT / ".claude-plugin" / "plugin.json"
MARKETPLACE = ROOT / ".claude-plugin" / "marketplace.json"
SERVER = ROOT / "server.json"

_HEADER = "<!-- Generated by scripts/gen_docs.py from the code. Do not edit by hand. -->\n"


def _type(schema: dict[str, Any]) -> str:
    if "anyOf" in schema:
        return " | ".join(_type(s) for s in schema["anyOf"] if s.get("type") != "null")
    if schema.get("type") == "array":
        return f"list[{_type(schema.get('items', {}))}]"
    return {"string": "str", "number": "float", "integer": "int", "boolean": "bool"}.get(
        schema.get("type", ""), "any"
    )


def _signature(name: str, schema: dict[str, Any]) -> str:
    required = set(schema.get("required", []))
    parts = [arg if arg in required else f"{arg}?" for arg in schema.get("properties", {})]
    return f"{name}({', '.join(parts)})"


def _paragraphs(text: str) -> list[str]:
    return [" ".join(p.split()) for p in text.strip().split("\n\n") if p.strip()]


def render_reference() -> str:
    tools = asyncio.run(mcp.list_tools())
    out = [_HEADER, "# Reference\n"]
    out.append(
        f"ardupilot-mcp {__version__}: {len(tools)} MCP tools and {len(get_checks())} checks. "
        "Every tool is read-only.\n"
    )

    out.append("## Tools\n")
    for tool in tools:
        schema = tool.input_schema or {}
        out.append(f"### `{_signature(tool.name, schema)}`\n")
        out.extend(p + "\n" for p in _paragraphs(tool.description or ""))
        props = schema.get("properties", {})
        if props:
            required = set(schema.get("required", []))
            out.append("| Argument | Type | Default |")
            out.append("|---|---|---|")
            for arg, spec in props.items():
                default = "required" if arg in required else f"`{json.dumps(spec.get('default'))}`"
                out.append(f"| `{arg}` | `{_type(spec)}` | {default} |")
            out.append("")

    out.append("## Checks\n")
    out.append(
        "Each check runs only when its messages are in the log and the vehicle and log type "
        "match. Thresholds and their sources are in [SOURCES.md](SOURCES.md).\n"
    )
    out.append("| Check | Category | Vehicles | Logs | Needs | What it reports |")
    out.append("|---|---|---|---|---|---|")
    for c in get_checks():
        vehicles = ", ".join(sorted(c.vehicles)) if c.vehicles else "all"
        logs = ", ".join(f"`.{'bin' if s == 'dataflash' else s}`" for s in sorted(c.sources))
        needs = ", ".join(f"`{m}`" for m in sorted(c.requires)) or "—"
        out.append(f"| `{c.id}` | {c.category} | {vehicles} | {logs} | {needs} | {c.description} |")
    out.append("")
    return "\n".join(out)


def _manifest(path: Path, update: Callable[[dict[str, Any]], None]) -> str:
    data = json.loads(path.read_text(encoding="utf-8"))
    update(data)
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def _plugin(data: dict[str, Any]) -> None:
    data["version"] = __version__
    data["license"] = LICENSE


def _marketplace(data: dict[str, Any]) -> None:
    for plugin in data.get("plugins", []):
        if plugin.get("name") == "ardupilot-mcp":
            plugin["version"] = __version__


def _server(data: dict[str, Any]) -> None:
    data["version"] = __version__
    for package in data.get("packages", []):
        package["version"] = __version__


def expected() -> dict[Path, str]:
    """Every generated file and the content it should have."""
    return {
        REFERENCE: render_reference(),
        PLUGIN: _manifest(PLUGIN, _plugin),
        MARKETPLACE: _manifest(MARKETPLACE, _marketplace),
        SERVER: _manifest(SERVER, _server),
    }


def stale() -> list[Path]:
    return [
        path
        for path, content in expected().items()
        if not path.exists() or path.read_text(encoding="utf-8") != content
    ]


def main(argv: list[str]) -> int:
    if "--check" in argv:
        paths = stale()
        for path in paths:
            print(f"out of date: {path.relative_to(ROOT)}")
        if paths:
            print("run: python scripts/gen_docs.py")
        return 1 if paths else 0
    for path, content in expected().items():
        path.write_text(content, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
