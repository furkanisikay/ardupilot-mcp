"""Regenerate the documentation and manifests that are derived from the code.

Usage::

    python scripts/gen_docs.py           # rewrite the generated files
    python scripts/gen_docs.py --check   # exit 1 if any of them is out of date

What it owns:

- ``docs/reference.md``: every MCP tool (signature and description, from the server)
  and every registered check (from the registry).
- The version in ``.claude-plugin/plugin.json``, ``.claude-plugin/marketplace.json``
  and ``server.json``, taken from ``ardupilot_mcp.__version__``, and the license in
  ``plugin.json``.
- The regions between ``<!-- gen:NAME -->`` and ``<!-- /gen:NAME -->`` in ``README.md``,
  ``README.en.md`` and ``bench/README.md``: the example output (from the demo log of
  ``examples/generate_demo_log.py``), the check count, the benchmark log count (from
  ``bench/real_crashes.json``) and the benchmark results (from ``bench/results.json``,
  which ``python -m bench.run --logs DIR --json bench/results.json`` refreshes). Text
  outside the markers stays hand-written.

``tests/test_docs_sync.py`` runs the check, so CI fails when a change to the code is
not reflected here.
"""

from __future__ import annotations

import asyncio
import json
import re
import sys
import tempfile
import tomllib
from collections.abc import Callable
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from ardupilot_mcp import __version__, diagnose, parse_bin  # noqa: E402
from ardupilot_mcp.checks import get_checks  # noqa: E402
from ardupilot_mcp.model import Severity  # noqa: E402
from ardupilot_mcp.server import mcp  # noqa: E402
from examples.generate_demo_log import build_crash_log  # noqa: E402

LICENSE = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]["license"]
REFERENCE = ROOT / "docs" / "reference.md"
PLUGIN = ROOT / ".claude-plugin" / "plugin.json"
MARKETPLACE = ROOT / ".claude-plugin" / "marketplace.json"
SERVER = ROOT / "server.json"
README_TR = ROOT / "README.md"
README_EN = ROOT / "README.en.md"
BENCH_README = ROOT / "bench" / "README.md"
BENCH_MANIFEST = ROOT / "bench" / "real_crashes.json"
BENCH_RESULTS = ROOT / "bench" / "results.json"

# Findings the README example shows: the first CRITICAL finding of each, in this order.
EXAMPLE_CHECKS = ("vibration", "attitude", "power")

_HEADER = "<!-- Generated by scripts/gen_docs.py from the code. Do not edit by hand. -->\n"


def _type(schema: dict[str, Any]) -> str:
    if "anyOf" in schema:
        return " | ".join(_type(s) for s in schema["anyOf"] if s.get("type") != "null")
    if schema.get("type") == "array":
        return f"list[{_type(schema.get('items', {}))}]"
    return {"string": "str", "number": "float", "integer": "int", "boolean": "bool"}.get(
        schema.get("type", ""), "any"
    )


def _signature(name: str, schema: dict[str, Any]) -> str:
    required = set(schema.get("required", []))
    parts = [arg if arg in required else f"{arg}?" for arg in schema.get("properties", {})]
    return f"{name}({', '.join(parts)})"


def _paragraphs(text: str) -> list[str]:
    return [" ".join(p.split()) for p in text.strip().split("\n\n") if p.strip()]


def render_reference() -> str:
    tools = asyncio.run(mcp.list_tools())
    out = [_HEADER, "# Reference\n"]
    out.append(
        f"ardupilot-mcp {__version__}: {len(tools)} MCP tools and {len(get_checks())} checks. "
        "Every tool is read-only.\n"
    )

    out.append("## Tools\n")
    for tool in tools:
        schema = tool.input_schema or {}
        out.append(f"### `{_signature(tool.name, schema)}`\n")
        out.extend(p + "\n" for p in _paragraphs(tool.description or ""))
        props = schema.get("properties", {})
        if props:
            required = set(schema.get("required", []))
            out.append("| Argument | Type | Default |")
            out.append("|---|---|---|")
            for arg, spec in props.items():
                default = "required" if arg in required else f"`{json.dumps(spec.get('default'))}`"
                out.append(f"| `{arg}` | `{_type(spec)}` | {default} |")
            out.append("")

    out.append("## Checks\n")
    out.append(
        "Each check runs only when its messages are in the log and the vehicle and log type "
        "match. Thresholds and their sources are in [SOURCES.md](SOURCES.md).\n"
    )
    out.append("| Check | Category | Vehicles | Logs | Needs | What it reports |")
    out.append("|---|---|---|---|---|---|")
    for c in get_checks():
        vehicles = ", ".join(sorted(c.vehicles)) if c.vehicles else "all"
        logs = ", ".join(f"`.{'bin' if s == 'dataflash' else s}`" for s in sorted(c.sources))
        needs = ", ".join(f"`{m}`" for m in sorted(c.requires)) or "—"
        out.append(f"| `{c.id}` | {c.category} | {vehicles} | {logs} | {needs} | {c.description} |")
    out.append("")
    return "\n".join(out)


def replace_region(text: str, name: str, body: str, *, source: str = "text") -> str:
    """Put ``body`` between the ``gen:NAME`` markers of ``text``.

    Raises ValueError unless each marker occurs exactly once, in order, so a deleted or
    pasted-twice marker fails the docs check instead of passing silently.
    """
    start, end = f"<!-- gen:{name} -->", f"<!-- /gen:{name} -->"
    n_start, n_end = text.count(start), text.count(end)
    if n_start != 1 or n_end != 1:
        raise ValueError(f"{source}: expected one {start} and one {end}, found {n_start} and {n_end}")
    i, j = text.index(start) + len(start), text.index(end)
    if j < i:
        raise ValueError(f"{source}: {end} comes before {start}")
    return text[:i] + body + text[j:]


def _first_sentence(text: str) -> str:
    return re.split(r"(?<=[.!?])\s+(?=[A-Z])", text.strip(), maxsplit=1)[0]


def render_example() -> str:
    """The README excerpt of ``examples/analyze.py`` on the deterministic demo log."""
    # ignore_cleanup_errors: on Windows the parser's mmap can outlive the reader briefly.
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        report = diagnose(parse_bin(build_crash_log(str(Path(tmp) / "demo.bin"))))
    summary = report.summary_text.splitlines()
    lines = [next(ln for ln in summary if ln.startswith("First anomaly"))]
    lines.append(next(ln for ln in summary if re.match(r"\d+ critical, ", ln)))
    width = max(len(c) for c in EXAMPLE_CHECKS)
    for check_id in EXAMPLE_CHECKS:
        f = next(
            (f for f in report.findings if f.check_id == check_id and f.severity == Severity.CRITICAL),
            None,
        )
        if f is None:
            raise ValueError(
                f"the demo log no longer has a CRITICAL {check_id} finding; update EXAMPLE_CHECKS"
            )
        when = f" @ {f.evidence.time_start_s:.0f}s" if f.evidence.time_start_s is not None else ""
        lines.append(f"[CRITICAL] {check_id:<{width}}{when}: {f.title}")
        lines.append(" " * 11 + _first_sentence(f.explanation))
    return "\n```text\n" + "\n".join(lines) + "\n```\n"


def render_bench() -> str:
    s = json.loads(BENCH_RESULTS.read_text(encoding="utf-8"))["summary"]
    entries = len(json.loads(BENCH_MANIFEST.read_text(encoding="utf-8"))["entries"])
    if s["logs"] != entries:
        raise ValueError(
            f"bench/results.json covers {s['logs']} of the {entries} logs in the manifest; "
            "re-run python -m bench.run with every log"
        )
    measured = s.get("measured_on") or {}
    rev = f" ({measured['revision']})" if measured.get("revision") else ""
    by_check = ", ".join(f"`{c}` {n}" for c, n in s["false_criticals_by_check"].items())
    total = s["false_criticals_total"]
    return (
        f"\nMeasured on ardupilot-mcp {measured.get('version', '?')}{rev}.\n\n"
        "| Scorable logs | Top-1 | Top-3 | Logs with a false critical | False criticals |\n"
        "|---|---|---|---|---|\n"
        f"| {s['scored']} | {s['top1_hits']} | {s['top3_hits']} | "
        f"{s['logs_with_false_critical']} / {s['logs']} | {total} |\n\n"
        f"False criticals by check: {by_check}. {s['false_criticals_before_impact']} of the "
        f"{total} start before the impact, so they reach the top of the report rather than "
        "the after-impact tail.\n"
    )


def _regions(path: Path, regions: dict[str, str]) -> str:
    text = path.read_text(encoding="utf-8")
    for name, body in regions.items():
        text = replace_region(text, name, body, source=str(path.relative_to(ROOT)))
    return text


def _manifest(path: Path, update: Callable[[dict[str, Any]], None]) -> str:
    data = json.loads(path.read_text(encoding="utf-8"))
    update(data)
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def _plugin(data: dict[str, Any]) -> None:
    data["version"] = __version__
    data["license"] = LICENSE


def _marketplace(data: dict[str, Any]) -> None:
    for plugin in data.get("plugins", []):
        if plugin.get("name") == "ardupilot-mcp":
            plugin["version"] = __version__


def _server(data: dict[str, Any]) -> None:
    data["version"] = __version__
    for package in data.get("packages", []):
        package["version"] = __version__


def expected() -> dict[Path, str]:
    """Every generated file and the content it should have."""
    readme = {
        "example": render_example(),
        "checks": str(len(get_checks())),
        "bench-logs": str(len(json.loads(BENCH_MANIFEST.read_text(encoding="utf-8"))["entries"])),
    }
    return {
        REFERENCE: render_reference(),
        PLUGIN: _manifest(PLUGIN, _plugin),
        MARKETPLACE: _manifest(MARKETPLACE, _marketplace),
        SERVER: _manifest(SERVER, _server),
        README_TR: _regions(README_TR, readme),
        README_EN: _regions(README_EN, readme),
        BENCH_README: _regions(BENCH_README, {"results": render_bench()}),
    }


def stale() -> list[Path]:
    return [
        path
        for path, content in expected().items()
        if not path.exists() or path.read_text(encoding="utf-8") != content
    ]


def main(argv: list[str]) -> int:
    if "--check" in argv:
        paths = stale()
        for path in paths:
            print(f"out of date: {path.relative_to(ROOT)}")
        if paths:
            print("run: python scripts/gen_docs.py")
        return 1 if paths else 0
    for path, content in expected().items():
        path.write_text(content, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
